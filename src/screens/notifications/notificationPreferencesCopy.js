export function getNotificationPreferencesCopy(language) {
  const code = String(language || 'en').toLowerCase().split('-')[0];
  const dictionary = Object.prototype.hasOwnProperty.call(notificationPreferenceTranslations, code) ? notificationPreferenceTranslations[code] : {};
  return text => dictionary[text] || text;
}
